"""Generate the integration activity from the pinned upstream camera, without changing decoders."""
from pathlib import Path
root = Path(__file__).resolve().parents[1]
source = (root / 'vendor/pcb-line-code-reader/src/org/datamatrix/linereader/MainActivity.java').read_text(encoding='utf-8')
def replace(old, new):
    global source
    if old not in source:
        raise RuntimeError('Upstream integration anchor changed')
    source = source.replace(old, new)
replace('public final class MainActivity extends Activity {', '''public final class InventoryScannerActivity extends Activity {
    private Button useCode;
    private boolean markedEngineVerified;
    private String selectedPayload, selectedFormat;
    private void clearSelection(){selectedPayload=null;selectedFormat=null;if(useCode!=null)useCode.setEnabled(false);}
''')
replace('qrMode=getSharedPreferences("scanner",0).getBoolean("qr_mode",false);', '''qrMode=getSharedPreferences("scanner",0).getBoolean("qr_mode",false);
        String requested=getIntent().getStringExtra("format");
        if("DATA_MATRIX".equals(requested))qrMode=false;else if("QR_CODE".equals(requested))qrMode=true;''')
replace('root.setOrientation(LinearLayout.VERTICAL);', '''getWindow().setDecorFitsSystemWindows(false);root.setOrientation(LinearLayout.VERTICAL);root.setLayoutDirection(View.LAYOUT_DIRECTION_LTR);
        root.setOnApplyWindowInsetsListener((v,i)->{v.setPadding(i.getSystemWindowInsetLeft(),i.getSystemWindowInsetTop(),i.getSystemWindowInsetRight(),i.getSystemWindowInsetBottom());return i;});''')
replace('root.addView(buttons);setContentView(root);', '''root.addView(buttons,3);
        useCode=new Button(this);useCode.setText("Use scanned code (local result)");useCode.setEnabled(false);
        useCode.setOnClickListener(v->{if(selectedPayload==null)return;setResult(RESULT_OK,new Intent().putExtra("payload",selectedPayload).putExtra("format",selectedFormat));finish();});
        root.addView(useCode,4,new LinearLayout.LayoutParams(-1,-2));setContentView(root);''')
replace('modeEpoch++;successUntil=0;', 'modeEpoch++;clearSelection();successUntil=0;')
replace('result.setText(decoded);', '''selectedPayload=decoded;selectedFormat=scanQr?"QR_CODE":"DATA_MATRIX";useCode.setEnabled(true);result.setText(decoded);''')
replace('if(value==null&&!scanQr)value=MarkedDecoder.decode(this,pixels,roi.width(),roi.height());', '''if(value==null&&!scanQr){
                value=MarkedDecoder.decode(this,pixels,roi.width(),roi.height());
                if(!markedEngineVerified){markedEngineVerified=true;android.util.Log.i("OzakScanner","Original OpenCV pipeline executed successfully");}
            }''')
# Diagnostic capture stays opt-in upstream; do not copy it into the inventory app.
begin=source.index('        java.io.File snapshot=')
end=source.index('        if(!analyzing.compareAndSet', begin)
source=source[:begin]+source[end:]
replace('android.util.Log.e("LineDecode","Frame decode failed",e);', 'error("Decode failed. Adjust focus or lighting and try again.");')
target=root/'scanner/src/main/java/org/datamatrix/linereader/InventoryScannerActivity.java'
target.parent.mkdir(parents=True,exist_ok=True)
target.write_text('// Adapted from pinned upstream; generated by tests/prepare_inventory_scanner.py\n'+source,encoding='utf-8')
print('Prepared upstream camera integration; decoder algorithms unchanged.')
